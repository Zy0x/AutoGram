pub fn is_fallback_black_card_bytes(b: &[u8]) -> bool {
    if b.is_empty() {
        return false;
    }
    // Solid dark card signature check
    b.len() < 256
}

pub fn find_ffmpeg_binary() -> Option<PathBuf> {
    if let Some(path) = which_path("ffmpeg") {
        return Some(path);
    }
    let mut search_dirs = Vec::new();
    if let Ok(cd) = std::env::current_dir() {
        let mut cur = Some(cd.as_path());
        while let Some(dir) = cur {
            search_dirs.push(dir.to_path_buf());
            cur = dir.parent();
        }
    }
    if let Ok(exe) = std::env::current_exe() {
        let mut cur = exe.parent();
        while let Some(dir) = cur {
            search_dirs.push(dir.to_path_buf());
            cur = dir.parent();
        }
    }

    let sub_paths = [
        "worker/venv/Lib/site-packages/imageio_ffmpeg/binaries",
        "AutoGram App/worker/venv/Lib/site-packages/imageio_ffmpeg/binaries",
        "../worker/venv/Lib/site-packages/imageio_ffmpeg/binaries",
        "../../worker/venv/Lib/site-packages/imageio_ffmpeg/binaries",
        "cache/bin",
        "bin",
    ];

    for base in &search_dirs {
        for sub in &sub_paths {
            let candidate_dir = base.join(sub);
            if candidate_dir.is_dir() {
                if let Ok(entries) = std::fs::read_dir(&candidate_dir) {
                    for entry in entries.flatten() {
                        let p = entry.path();
                        if p.is_file() {
                            let name = p.file_name().unwrap_or_default().to_string_lossy().to_lowercase();
                            if name.starts_with("ffmpeg") && (name.ends_with(".exe") || !cfg!(windows)) {
                                return Some(p);
                            }
                        }
                    }
                }
            }
        }
    }

    if cfg!(windows) {
        let mut win_dirs = Vec::new();
        if let Ok(pf) = std::env::var("ProgramFiles") {
            win_dirs.push(PathBuf::from(pf));
        }
        if let Ok(pfx86) = std::env::var("ProgramFiles(x86)") {
            win_dirs.push(PathBuf::from(pfx86));
        }
        if let Ok(local_app) = std::env::var("LOCALAPPDATA") {
            win_dirs.push(PathBuf::from(local_app));
        }
        win_dirs.push(PathBuf::from("C:\\ffmpeg"));
        win_dirs.push(PathBuf::from("C:\\Tools"));

        for base in win_dirs {
            if let Some(p) = search_ffmpeg_recursive(&base, 4) {
                return Some(p);
            }
        }
    }

    None
}

fn search_ffmpeg_recursive(dir: &Path, max_depth: usize) -> Option<PathBuf> {
    if max_depth == 0 || !dir.is_dir() {
        return None;
    }
    if let Ok(entries) = std::fs::read_dir(dir) {
        let mut subdirs = Vec::new();
        for entry in entries.flatten() {
            let p = entry.path();
            if p.is_file() {
                let name = p.file_name().unwrap_or_default().to_string_lossy().to_lowercase();
                if name.starts_with("ffmpeg") && (name.ends_with(".exe") || !cfg!(windows)) {
                    return Some(p);
                }
            } else if p.is_dir() {
                subdirs.push(p);
            }
        }
        for sub in subdirs {
            if let Some(found) = search_ffmpeg_recursive(&sub, max_depth - 1) {
                return Some(found);
            }
        }
    }
    None
}

fn which_path(cmd: &str) -> Option<PathBuf> {
    let path_var = std::env::var_os("PATH")?;
    for dir in std::env::split_paths(&path_var) {
        let full = if cfg!(windows) { dir.join(format!("{cmd}.exe")) } else { dir.join(cmd) };
        if full.is_file() {
            return Some(full);
        }
    }
    None
}
