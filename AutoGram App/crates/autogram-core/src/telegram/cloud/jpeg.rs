#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rejects_invalid_data() {
        assert!(unstrip_jpeg(&[]).is_none());
        assert!(unstrip_jpeg(&[0x01]).is_none());
        assert!(unstrip_jpeg(&[0x01, 40]).is_none());
        // Non-stripped data (byte 0 != 0x01)
        assert!(unstrip_jpeg(&[0xff, 0xd8, 0xff]).is_none());
    }

    #[test]
    fn unstrips_valid_stripped_jpeg() {
        let dummy_scan = [0x12, 0x34, 0x56, 0x78];
        let stripped = [0x01, 40, 30, 0x12, 0x34, 0x56, 0x78];
        let unstripped = unstrip_jpeg(&stripped).expect("valid unstrip");

        // Verify standard JFIF JPEG header
        assert_eq!(&unstripped[0..4], &[0xff, 0xd8, 0xff, 0xe0]);
        // Verify JFIF identifier
        assert_eq!(&unstripped[6..10], b"JFIF");
        // Verify EOF marker
        let len = unstripped.len();
        assert_eq!(&unstripped[len - 2..len], &[0xff, 0xd9]);
        // Verify scan bytes are present
        assert_eq!(&unstripped[len - 6..len - 2], &dummy_scan);
    }

    #[test]
    fn embeds_dimensions_into_frame() {
        let stripped = [0x01, 64, 48, 0xaa];
        let unstripped = unstrip_jpeg(&stripped).unwrap();
        // Look for SOF0 marker: 0xff, 0xc0, 0x00, 0x11, 0x08, height, width
        let sof0_pos = unstripped
            .windows(5)
            .position(|w| w == [0xff, 0xc0, 0x00, 0x11, 0x08])
            .expect("SOF0 marker found");
        assert_eq!(unstripped[sof0_pos + 5], 48); // height
        assert_eq!(unstripped[sof0_pos + 6], 64); // width
    }
}
